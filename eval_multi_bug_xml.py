def save_data_in_json(file_path,data):
    with open(file_path,'w') as f:
        json.dump(data,f,indent=4,default=str)

def run_eval_global(domain,output_file,num_inputs=10000,mode="no-generate",R=3):
    try:
        with open(output_file,'r') as f:
            all_res=json.load(f)
    except:
        all_res={}
        with open(output_file,'w') as f:
            json.dump(all_res,f,indent=4)
        
    
    print("Evaluation multi bug for the seeds...")
    res_seeds = run_eval_seeds(domain)
    all_res["Seeds"]=res_seeds
    save_data_in_json(output_file,all_res)

    print("Evaluation multi bug for Grammarinator...")
    res_gram = run_eval_Grammarinator(domain,mode,num_inputs,R)
    all_res["Grammarinator"] = res_gram
    save_data_in_json(output_file,all_res)

    print("Evaluation multi bug for ExplainFuzz...")
    res_ef = run_eval_ExplainFuzz(domain,mode,num_inputs=num_inputs,R=R)
    all_res["ExplainFuzz"] = res_ef
    save_data_in_json(output_file,all_res)

    print(f"🎉 Evaluation complete. Results saved to {output_file}")

    return all_res

def run_eval_conditioning(domain,res_file_path,save_file_path,nb_inputs=10000,R=3,mode="no-generate"):
    all_res={}
    with open(res_file_path, "r") as f:
        all_res = json.load(f)
    
    results_conditioning=[]
    tokens_covered = set()
    

    for _,bug_info in BUG_SPECS_XML.items():
        tok_condition = bug_info.get("cond_token",None)
        if tok_condition in tokens_covered:
            continue
       
        results_one_condition=[]
        for _ in range(R):
            start = time()
            print(f"Evaluating conditioning for tok condition {tok_condition}...")
            main_generate_inputs(domain, mode=mode, nb_concrete_inputs=nb_inputs,token_condition=tok_condition)
            folder_path = f"data/output/inputs/{domain}/test_inputs_{mode.replace('-','_')}"
            res_conditioned = run_multi_bug_eval_xml_on_folder(folder_path, allow_xxe=True)
            res_conditioned["conditioning_token"] = tok_condition
            results_one_condition.append(res_conditioned)
            tokens_covered.add(tok_condition)
            end=time()
            print(f"Evaluation took {round(end-start,0)} s")
        results_conditioning.append(results_one_condition)

    # Try with a sequence 5xEntityRef
    results_one_condition=[]
    tok_condition = ["EntityRef"]*5 
    for _ in range(R):
        start = time()
        print(f"Evaluating conditioning for tok condition 5 EntityRef...")
        main_generate_inputs(domain, mode=mode, nb_concrete_inputs=nb_inputs,token_condition=tok_condition)
        folder_path = f"data/output/inputs/{domain}/test_inputs_{mode.replace('-','_')}"
        res_conditioned = run_multi_bug_eval_xml_on_folder(folder_path, allow_xxe=True)
        res_conditioned["conditioning_token"] = "5xEntityRef"
        results_one_condition.append(res_conditioned)
        
        end=time()
        print(f"Evaluation took {round(end-start,0)} s")
    results_conditioning.append(results_one_condition)
    
    all_res["ExplainFuzz + conditioning"] = results_conditioning
    with open(save_file_path, "w") as f:
        json.dump(all_res, f, indent=4)
    
    return all_res

def find_xpath(folder):
    p = Path(folder)
    input_with_xpath = []
    files = sorted([x for x in p.iterdir() if x.is_file() and x.suffix in ('.xml','.txt')])
    for file in files:
        with open(file, "r", encoding="utf-8") as f:
            input = f.read()
        if "name[" in input:
            input_with_xpath.append(file)
    return input_with_xpath

