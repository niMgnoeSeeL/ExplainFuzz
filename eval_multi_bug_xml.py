def clean_generated_xml(xml_text: str) -> str:
    """
    Cleans up XML generated by Grammarinator:
    - Removes spaces after '<' and before '>'
    - Removes spaces around '=' in attributes
    - Collapses multiple spaces into one where appropriate
    - Preserves spaces in text content and CDATA sections
    """
    
    # Remove spaces immediately after '<' and before '>'
    xml_text = re.sub(r'<\s+', '<', xml_text)
    xml_text = re.sub(r'\s+>', '>', xml_text)
    
    # Remove spaces in closing tags (must come after <\s+ cleanup)
    xml_text = re.sub(r'</\s*([a-zA-Z_:][\w:.-]*)\s*>', r'</\1>', xml_text)

    # Remove spaces around '=' in attributes
    xml_text = re.sub(r'\s*=\s*', '=', xml_text)

    # Remove spaces before '/>' for self-closing tags
    xml_text = re.sub(r'\s+/>\s*', '/>', xml_text)

    # Remove spaces between adjacent tags like '> <'
    xml_text = re.sub(r'>\s+<', '><', xml_text)

    # Strip leading/trailing whitespace on each line
    lines = xml_text.splitlines()
    lines = [line.strip() for line in lines if line.strip() != '']

    return '\n'.join(lines)

def clean_folder_xml_inputs(folder_path):
    for root, _, files in os.walk(folder_path):
        for filename in files:
            if filename.endswith(".txt") or filename.endswith(".xml"):
                file_path = os.path.join(root, filename)
                # Read the original XML content
                with open(file_path, "r", encoding="utf-8") as f:
                    xml_text = f.read()

                # Clean the XML
                new_xml_text = clean_generated_xml(xml_text)

                # Rewrite the file with the cleaned XML
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write(new_xml_text)


def run_eval_ExplainFuzz(domain,mode,num_inputs=10000,R=3):
    res_ExplainFuzz=[]
    folder_path = f"data/output/inputs/{domain}/test_inputs_{mode.replace('-','_')}"
    for _ in range(R):
        start = time()
        main_generate_inputs(domain, mode, num_inputs,None)
        print("Running the multi-bug eval...")
        res_ef_k = run_multi_bug_eval_xml_on_folder(folder_path, allow_xxe=True)
        res_ExplainFuzz.append(res_ef_k)
        end = time()
        print(f"Evaluation took {end-start} s")
    
    return res_ExplainFuzz

def run_eval_Grammarinator(domain,mode,num_inputs=10000,R=3):
    results_gram = []
    for try_id in range(1,R+1):
        folder_path = f"data/intermediate/fuzz_outputs/{domain}/try-{try_id}/{mode}/"
        # Clean the results to give Grammarinator a chance
        clean_folder_xml_inputs(folder_path)
        # Run the evaluation
        res_gramm = run_multi_bug_eval_xml_on_folder(folder_path,allow_xxe=True)
        results_gram.append(res_gramm)
    
    return results_gram

